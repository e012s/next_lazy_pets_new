export function repairOrderAsAssignment(order) {
    return {
        id: order.id,
        tab:
            order.status === "done"
                ? "done"
                : order.status === "upcoming"
                  ? "upcoming"
                  : "today",
        status: order.status,
        kind: "repair",
        detailLayout: "repair",
        title: order.title,
        code: order.code,
        subtitle: order.subtitle ?? "維修服務",
        badge: order.badge,
        badgeTone:
            order.badgeTone ??
            (order.status === "done" ? "ok" : order.status === "upcoming" ? "brand" : "alert"),
        payMain: order.payMain ?? order.pay,
        payNote: order.payNote,
        listIcon: order.listIcon,
        pay: order.pay,
        scheduleLabel: "服務時間",
        schedule: order.schedule,
        scheduleDetail: order.status === "done"
            ? (order.scheduleDetail ?? order.schedule)
            : (order.scheduleDetail ?? repairJob.rows.find((r) => r.label === "指定服務日期")?.value ?? order.schedule),
        placeLabel: "地址",
        place: order.place,
        mapQuery: order.place,
        contactName: order.contactName,
        contactPhone: order.contactPhone,
        note: order.note,
        serviceMonth: order.serviceMonth,
        doneList: order.doneList,
        metaLines: [`${repairJob.published} • ${repairJob.expires}`],
        quoteMain: order.quoteMain,
        quoteBudget: order.quoteBudget,
        repairDetailText: order.repairDetailText ?? (order.status === "done" ? order.note : repairJob.listDetail),
        area: order.area,
        reports: order.reports,
        completedDetail: order.completedDetail,
        completionGallery: order.completionGallery,
    };
}

/** All orders on 我的訂單 (pet + repair). */
export function listMyOrders() {
    return [...assignments, ...repairOrders.map(repairOrderAsAssignment)];
}

export function getAssignment(id) {
    return listMyOrders().find((order) => order.id === id);
}
